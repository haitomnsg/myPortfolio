"""Wordmark geometry for the Joint logo ("Ashish Gupta", A and G drawn as robot arms).
usage: python -I build_wordmark.py <RethinkSans-ExtraBold.ttf> <out.ts>

Get the font with
  curl -A "Mozilla/4.0" "https://fonts.googleapis.com/css2?family=Rethink+Sans:wght@800"
and download the .ttf url it lists (a static ExtraBold instance, 1000 units per em).

The A and G are drawn in code (src/components/Wordmark.tsx) from the metrics written here; "shish" and
"upta" are outlined from the font with its kerning, so the logo never depends on the web font loading.
Everything is in a 100-unit em with the baseline at y = 0, matching the canvas measurements the
explorations in assets/logo/explore/ were tuned with.
"""
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

F = 100


def kern_lookup(font):
    """Pair adjustments from the GPOS lookups behind the 'kern' feature: the first subtable that
    covers the first glyph decides, per lookup, the way HarfBuzz applies them."""
    gpos = font['GPOS'].table
    idx = sorted({i for fr in gpos.FeatureList.FeatureRecord if fr.FeatureTag == 'kern' for i in fr.Feature.LookupListIndex})
    lookups = []
    for i in idx:
        lk, subs = gpos.LookupList.Lookup[i], []
        for st in lk.SubTable:
            if lk.LookupType == 9:
                if st.ExtensionLookupType != 2:
                    continue
                st = st.ExtSubTable
            elif lk.LookupType != 2:
                continue
            subs.append(st)
        lookups.append(subs)

    def value(a, b):
        total = 0
        for subs in lookups:
            for st in subs:
                cov = st.Coverage.glyphs
                if a not in cov:
                    continue
                if st.Format == 1:
                    rec = next((r for r in st.PairSet[cov.index(a)].PairValueRecord if r.SecondGlyph == b), None)
                    if rec is None:
                        continue
                    v = rec.Value1
                else:
                    c1, c2 = st.ClassDef1.classDefs.get(a, 0), st.ClassDef2.classDefs.get(b, 0)
                    v = st.Class1Record[c1].Class2Record[c2].Value1
                total += (getattr(v, 'XAdvance', 0) or 0) if v else 0
                break
        return total

    return value


def main(src, out):
    font = TTFont(src)
    s = F / font['head'].unitsPerEm
    cmap, gs, hmtx = font.getBestCmap(), font.getGlyphSet(), font['hmtx']
    kern = kern_lookup(font)
    name = lambda ch: cmap[ord(ch)]

    def bounds(ch):
        pen = BoundsPen(gs)
        gs[name(ch)].draw(pen)
        return pen.bounds  # xMin, yMin, xMax, yMax in font units

    def adv(ch):
        return hmtx[name(ch)][0]

    def run(text):
        """Pen x of each glyph (font units) with kerning, and the total advance."""
        xs, x = [], 0
        for i, ch in enumerate(text):
            xs.append(x)
            x += adv(ch) + (kern(name(ch), name(text[i + 1])) if i + 1 < len(text) else 0)
        return xs, x

    def outline(text, x0):
        xs, _ = run(text)
        pen = SVGPathPen(gs, ntos=lambda v: f'{v:.2f}'.rstrip('0').rstrip('.'))
        for ch, x in zip(text, xs):
            gs[name(ch)].draw(TransformPen(pen, (s, 0, 0, -s, x0 + x * s, 0)))
        return pen.getCommands()

    A, G, H, I, p = bounds('A'), bounds('G'), bounds('H'), bounds('I'), bounds('p')
    geo = {
        'capH': H[3] * s,
        'w': (I[2] - I[0]) * s,  # stem of the ExtraBold: the arm links use it
        # the arm A is drawn a little wider than the font's so the piston has room; both arms get air after them
        'A': {'l': A[0] * s - .03 * F, 'r': A[2] * s + .03 * F, 'adv': adv('A') * s + .07 * F},
        'G': {'l': G[0] * s, 'r': G[2] * s, 't': -G[3] * s, 'b': -G[1] * s, 'adv': adv('G') * s + .05 * F},
        'desc': -p[1] * s,
    }
    geo['gx'] = geo['A']['adv'] + run('shish ')[1] * s
    geo['ux'] = geo['gx'] + geo['G']['adv']
    xs, _ = run('upta')
    geo['right'] = geo['ux'] + (xs[-1] + bounds('a')[2]) * s

    num = lambda v: f'{v:.2f}'.rstrip('0').rstrip('.')
    fmt = lambda d: '{ ' + ', '.join(f'{k}: {fmt(v) if isinstance(v, dict) else num(v)}' for k, v in d.items()) + ' }'
    with open(out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('// Generated by tools/logo/build_wordmark.py from Rethink Sans ExtraBold. Do not edit by hand.\n')
        fh.write(f'export const METRICS = {fmt(geo)} as const;\n\n')
        fh.write(f"export const SHISH = '{outline('shish', geo['A']['adv'])}';\n\n")
        fh.write(f"export const UPTA = '{outline('upta', geo['ux'])}';\n")
    print({k: v for k, v in geo.items()})


if __name__ == '__main__':
    main(*sys.argv[1:3])
